import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { useState } from "react";
import { fetchAITrafficReport } from "@/lib/ga4.functions";
import type { AITrafficReport } from "@/lib/ai-sources";

export const Route = createFileRoute("/results")({
  validateSearch: (search) => ({
    propertyId: (search.propertyId as string) || "",
    propertyName: (search.propertyName as string) || "",
  }),
  loaderDeps: ({ search }) => ({
    propertyId: search.propertyId,
    propertyName: search.propertyName,
  }),
  head: () => ({
    meta: [
      { title: "Your AI Traffic — Is AI Sending Me Traffic?" },
      { name: "description", content: "Your AI traffic analysis results." },
    ],
  }),
  loader: async ({ deps }) => {
    if (!deps.propertyId) {
      return { report: null, error: "no_property" };
    }
    try {
      const result = await fetchAITrafficReport({
        data: {
          propertyId: deps.propertyId,
          propertyName: deps.propertyName,
        },
      });
      return { report: result.report, error: null };
    } catch (e: unknown) {
      console.error("Report fetch failed:", e);
      return { report: null, error: (e as Error).message || "unknown" };
    }
  },
  pendingComponent: LoadingState,
  component: ResultsPage,
});

function LoadingState() {
  return (
    <div className="min-h-screen bg-background flex items-center justify-center px-6">
      <div className="text-center space-y-3">
        <div className="w-8 h-8 border-2 border-primary border-t-transparent rounded-full animate-spin mx-auto" />
        <p className="text-muted-foreground animate-pulse">
          Looking for AI referral traffic...
        </p>
        <p className="text-xs text-muted-foreground/60">
          This usually takes a few seconds
        </p>
      </div>
    </div>
  );
}

function ResultsPage() {
  const { report, error } = Route.useLoaderData();
  const navigate = useNavigate();
  const [copied, setCopied] = useState(false);

  if (error || !report) {
    return (
      <div className="min-h-screen bg-background flex items-center justify-center px-6">
        <div className="text-center space-y-4 max-w-sm">
          <h1 className="text-xl font-bold text-foreground">
            Something went wrong
          </h1>
          <p className="text-sm text-muted-foreground">
            {error === "no_property"
              ? "No property selected."
              : "We couldn't fetch your analytics data. Please try again."}
          </p>
          <div className="flex gap-3 justify-center">
            <Link
              to="/connect"
              className="rounded-xl bg-primary px-5 py-2.5 text-sm font-semibold text-primary-foreground"
            >
              Try again
            </Link>
            <Link
              to="/"
              className="rounded-xl bg-secondary px-5 py-2.5 text-sm font-semibold text-secondary-foreground"
            >
              Go home
            </Link>
          </div>
        </div>
      </div>
    );
  }

  const shareText =
    report.state === "none"
      ? `I checked whether AI tools are sending traffic to my site. Not yet — but it's worth keeping an eye on.`
      : `I connected GA4 and found that AI tools already sent us ${report.totalAISessions} visits in the last 30 days.${report.topSource ? ` Most came from ${report.topSource.label}` : ""}${report.topPage ? ` and landed on ${report.topPage.path}` : ""}. Worth a look.`;

  const shortShareText =
    report.state !== "none"
      ? `Apparently AI is already sending us traffic and GA4 hides this pretty badly.`
      : `Checked for AI traffic in my GA4 — nothing yet, but worth monitoring.`;

  const handleCopy = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // fallback
    }
  };

  const handleEmail = () => {
    const subject = encodeURIComponent("Your AI Traffic Check result");
    const body = encodeURIComponent(
      `Here's your AI traffic summary for ${report.propertyName}:\n\n` +
        `Date range: ${report.dateRange.start} to ${report.dateRange.end}\n` +
        `AI visits: ${report.totalAISessions}\n` +
        (report.topSource
          ? `Top source: ${report.topSource.label} (${report.topSource.sessions} sessions)\n`
          : "") +
        (report.topPage
          ? `Top landing page: ${report.topPage.path}\n`
          : "") +
        `\n---\nGenerated by IsAISendingMeTraffic.com`
    );
    window.location.href = `mailto:?subject=${subject}&body=${body}`;
  };

  return (
    <div className="min-h-screen bg-background">
      <div className="max-w-lg mx-auto px-6 py-8">
        {/* Property name */}
        <p className="text-xs text-muted-foreground mb-6 uppercase tracking-wider">
          {report.propertyName} · Last 30 days
        </p>

        {/* Hero result card */}
        <div className="rounded-2xl border border-border bg-card p-6 mb-6 shadow-sm">
          <HeroCard report={report} />
        </div>

        {/* Source breakdown */}
        {report.sourceBreakdown.length > 0 && (
          <section className="mb-6">
            <h2 className="text-sm font-semibold text-foreground mb-3">
              AI traffic by source
            </h2>
            <div className="space-y-2">
              {report.sourceBreakdown.map((s: { source: string; label: string; category: string; sessions: number; users: number }) => (
                <div
                  key={s.source}
                  className="flex items-center justify-between rounded-xl border border-border bg-card px-4 py-3"
                >
                  <div>
                    <p className="text-sm font-medium text-card-foreground">
                      {s.label}
                    </p>
                    <p className="text-xs text-muted-foreground">{s.source}</p>
                  </div>
                  <div className="text-right">
                    <p className="text-sm font-semibold text-card-foreground">
                      {s.sessions}
                    </p>
                    <p className="text-xs text-muted-foreground">sessions</p>
                  </div>
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Top pages */}
        {report.topPages.length > 0 && (
          <section className="mb-6">
            <h2 className="text-sm font-semibold text-foreground mb-3">
              Top pages getting AI traffic
            </h2>
            <div className="space-y-2">
              {report.topPages.slice(0, 5).map((p: { path: string; sessions: number }) => (
                <div
                  key={p.path}
                  className="flex items-center justify-between rounded-xl border border-border bg-card px-4 py-3"
                >
                  <p className="text-sm text-card-foreground truncate mr-4 flex-1">
                    {p.path}
                  </p>
                  <p className="text-sm font-semibold text-card-foreground whitespace-nowrap">
                    {p.sessions}
                  </p>
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Trend chart */}
        {report.dailyTrend.length > 0 && (
          <section className="mb-6">
            <h2 className="text-sm font-semibold text-foreground mb-3">
              30-day trend
            </h2>
            <TrendChart data={report.dailyTrend} />
          </section>
        )}

        {/* Zero-data state */}
        {report.state === "none" && (
          <ZeroState
            topOrganicPages={report.topOrganicPages}
          />
        )}

        {/* What this means */}
        <section className="mb-6">
          <h2 className="text-sm font-semibold text-foreground mb-3">
            What this means
          </h2>
          <div className="rounded-xl border border-border bg-card p-4 space-y-3">
            <WhatThisMeans report={report} />
          </div>
        </section>

        {/* Disclaimer */}
        <p className="text-xs text-muted-foreground/70 mb-8 leading-relaxed">
          This is likely a partial view. Some AI visits may not be clearly
          attributed in GA4. AI traffic is probably undercounted because some
          visits may be unattributed or grouped elsewhere.
        </p>

        {/* Share actions */}
        <section className="mb-8 space-y-2">
          <button
            onClick={() => handleCopy(shareText)}
            className="w-full rounded-xl border border-border bg-card px-4 py-3 text-sm font-medium text-card-foreground hover:border-primary/40 transition-colors text-left"
          >
            {copied ? "✓ Copied!" : "📋 Copy summary to share"}
          </button>

          <button
            onClick={() => handleCopy(shortShareText)}
            className="w-full rounded-xl border border-border bg-card px-4 py-3 text-sm font-medium text-card-foreground hover:border-primary/40 transition-colors text-left"
          >
            📋 Copy short version
          </button>

          <button
            onClick={handleEmail}
            className="w-full rounded-xl border border-border bg-card px-4 py-3 text-sm font-medium text-card-foreground hover:border-primary/40 transition-colors text-left"
          >
            ✉️ Email this to myself
          </button>

          <Link
            to="/connect"
            className="block w-full rounded-xl border border-border bg-card px-4 py-3 text-sm font-medium text-card-foreground hover:border-primary/40 transition-colors text-left"
          >
            🔄 Check another site
          </Link>
        </section>

        {/* Soft CTA */}
        <section className="rounded-2xl border border-primary/20 bg-primary/5 p-6 mb-8 text-center">
          <p className="text-sm font-medium text-foreground mb-2">
            Want to grow this channel, not just measure it?
          </p>
          <a
            href="https://lovedbyai.com"
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center justify-center rounded-xl bg-primary px-5 py-2.5 text-sm font-semibold text-primary-foreground hover:bg-primary/90 transition-colors"
          >
            See how LovedByAI helps
          </a>
        </section>

        {/* Footer */}
        <footer className="pb-8 text-center">
          <p className="text-xs text-muted-foreground/60">
            With ❤️ by{" "}
            <a
              href="https://lovedbyai.com"
              target="_blank"
              rel="noopener noreferrer"
              className="underline"
            >
              lovedbyai
            </a>
          </p>
        </footer>
      </div>
    </div>
  );
}

function HeroCard({ report }: { report: AITrafficReport }) {
  const headlines: Record<AITrafficReport["state"], string> = {
    meaningful: "AI is already sending visitors to your site",
    low: "You may already be getting a little AI traffic",
    none: "We did not find meaningful AI traffic yet",
  };

  return (
    <div className="text-center space-y-4">
      <h1 className="text-xl font-bold text-foreground leading-snug">
        {headlines[report.state]}
      </h1>

      {report.state !== "none" && (
        <div className="grid grid-cols-2 gap-4 pt-2">
          <div>
            <p className="text-3xl font-extrabold text-primary">
              {report.totalAISessions}
            </p>
            <p className="text-xs text-muted-foreground mt-1">
              AI visits (30d)
            </p>
          </div>
          <div>
            <p className="text-3xl font-extrabold text-foreground">
              {report.changePercent !== null ? (
                <span
                  className={
                    report.changePercent > 0
                      ? "text-primary"
                      : report.changePercent < 0
                        ? "text-destructive"
                        : ""
                  }
                >
                  {report.changePercent > 0 ? "+" : ""}
                  {report.changePercent}%
                </span>
              ) : (
                "—"
              )}
            </p>
            <p className="text-xs text-muted-foreground mt-1">
              vs prev 30 days
            </p>
          </div>
        </div>
      )}

      {report.topSource && (
        <p className="text-sm text-muted-foreground">
          Top source:{" "}
          <span className="font-medium text-foreground">
            {report.topSource.label}
          </span>
        </p>
      )}

      {report.topPage && (
        <p className="text-sm text-muted-foreground">
          Top page:{" "}
          <span className="font-medium text-foreground">
            {report.topPage.path}
          </span>
        </p>
      )}
    </div>
  );
}

function TrendChart({ data }: { data: Array<{ date: string; sessions: number }> }) {
  const maxSessions = Math.max(...data.map((d) => d.sessions), 1);

  return (
    <div className="rounded-xl border border-border bg-card p-4">
      <div className="flex items-end gap-0.5 h-24">
        {data.map((d) => {
          const height = (d.sessions / maxSessions) * 100;
          return (
            <div
              key={d.date}
              className="flex-1 bg-primary/80 rounded-t-sm hover:bg-primary transition-colors"
              style={{ height: `${Math.max(height, 2)}%` }}
              title={`${d.date}: ${d.sessions} sessions`}
            />
          );
        })}
      </div>
      <div className="flex justify-between mt-2">
        <p className="text-[10px] text-muted-foreground">
          {data[0]?.date?.slice(4, 8)}
        </p>
        <p className="text-[10px] text-muted-foreground">
          {data[data.length - 1]?.date?.slice(4, 8)}
        </p>
      </div>
    </div>
  );
}

